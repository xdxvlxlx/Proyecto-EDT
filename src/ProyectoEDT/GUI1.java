    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (hashTable.esVacia()) {
            String texto = "No se puede Cargar la Tabla Hash porque esta Vacia";
            jTextArea1.setText(texto);
        } else {
        String texto = "Valores de la Tabla Hash\n";
        for (int i = 0; i < hashTable.getHashTable().length; i++) {
            Object miObjeto = hashTable.getHashTable()[i];
            if (miObjeto instanceof Estacion) {
                texto += "\n["+i+"] "+((Estacion)miObjeto).getNombreEstacion() + "  -> null";
            } else if (miObjeto instanceof Nodo) {
                miObjeto = (Nodo) miObjeto;
                String linea = "";
                while (miObjeto != null) {
                    linea += ((Nodo) miObjeto).getEstacion().getNombreEstacion()+"  ->  ";
                    miObjeto = ((Nodo) miObjeto).getNext();
                }
                linea += "null";
                texto += "\n["+i+"] ";
                texto += linea;
            } else if (miObjeto == null) {
                texto += "\n["+i+"] null";
            }
            jTextArea1.setText(texto);
        }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

